"""Update the authored courtyard in place, preserving pre-cut floor meshes."""
import bpy, json
from pathlib import Path
from mathutils import Vector
OUT=Path(r'C:\Users\huske\Desktop\project-mil\artifacts\lobby-layout')
scene=bpy.context.scene
assert scene.name=='Energy Core - Courtyard Layout Only', 'Select the authored courtyard scene first'
structure=bpy.data.collections['LAYOUT - Export This']
guides=bpy.data.collections['PLANNING GUIDES - Do Not Export']
root=bpy.data.objects['EnergyCore_CourtyardLayout']
assert not any(o.name=='Mine shaft - west' for o in structure.objects),'Mine is already installed'

# Only change materials owned by this layout; the ore collection stays untouched.
materials={m for o in structure.all_objects if o.type=='MESH' for m in o.data.materials if m}
for mat in materials:
 rgb=mat.diffuse_color[:3]
 has_texture=any(node.type=='TEX_IMAGE' for node in mat.node_tree.nodes)
 color=(tuple(c/12.92 if c<=.04045 else ((c+.055)/1.055)**2.4 for c in rgb)+(1,)) if has_texture else tuple(mat.diffuse_color)
 for node in list(mat.node_tree.nodes):
  if node.type=='TEX_IMAGE': mat.node_tree.nodes.remove(node)
 mat.diffuse_color=color
 bs=mat.node_tree.nodes.get('Principled BSDF')
 bs.inputs['Base Color'].default_value=color
 bs.inputs['Roughness'].default_value=.82

def box(name,loc,size,material):
 sx,sy,sz=[v/2 for v in size]
 verts=[(-sx,-sy,-sz),(sx,-sy,-sz),(sx,sy,-sz),(-sx,sy,-sz),(-sx,-sy,sz),(sx,-sy,sz),(sx,sy,sz),(-sx,sy,sz)]
 faces=[(0,3,2,1),(0,1,5,4),(1,2,6,5),(2,3,7,6),(3,0,4,7),(4,5,6,7)]
 mesh=bpy.data.meshes.new(name);mesh.from_pydata(verts,[],faces);mesh.update()
 ob=bpy.data.objects.new(name,mesh);structure.objects.link(ob);ob.parent=root
 ob.location=loc;mesh.materials.append(material);return ob

# Partition floor rectangles around the opening; no floor mesh crosses the shaft.
archive=bpy.data.collections.new('PRE-MINE FLOOR BACKUP - excluded')
scene.collection.children.link(archive)
archive.hide_render=True;archive.hide_viewport=True
for ob in list(structure.objects):
 if ob.type!='MESH':continue
 x,y,z=ob.location;w,d,h=ob.dimensions
 if z+h/2>.4 or z-h/2< -10:continue
 x0,x1=x-w/2,x+w/2;y0,y1=y-d/2,y+d/2
 if x1<=-36 or x0>=36 or y1<=-36 or y0>=36:continue
 ix0,ix1=max(x0,-36),min(x1,36)
 strips=[(x0,min(x1,-36),y0,y1),(max(x0,36),x1,y0,y1),
         (ix0,ix1,y0,min(y1,-36)),(ix0,ix1,max(y0,36),y1)]
 for i,(a,b,c,e) in enumerate(strips):
  if b-a>.0001 and e-c>.0001:
   box(ob.name+f'_MineCut_{i}',((a+b)/2,(c+e)/2,z),(b-a,e-c,h),ob.data.materials[0])
 structure.objects.unlink(ob);archive.objects.link(ob)

stone=bpy.data.materials['Walkway - cool grey']
dark=bpy.data.materials['Trim - graphite']
soil=bpy.data.materials['Cliff - deep strata']
# Four wide sides of a continuous 100 x 108 plaza, leaving a 72 x 72 clear opening.
box('Mine plaza - west',(-43,0,.19),(14,108,.08),stone)
box('Mine plaza - east',(43,0,.19),(14,108,.08),stone)
box('Mine plaza - south',(0,-45,.19),(72,18,.08),stone)
box('Mine plaza - north',(0,45,.19),(72,18,.08),stone)
for x in [-37,37]:box('Mine lip - '+str(x),(x,0,.29),(2,76,.14),dark)
for y in [-37,37]:box('Mine lip - '+str(y),(0,y,.29),(72,2,.14),dark)
box('Mine shaft - west',(-37,0,-361),(2,76,722),soil)
box('Mine shaft - east',(37,0,-361),(2,76,722),soil)
box('Mine shaft - north',(0,37,-361),(72,2,722),soil)
box('Mine shaft - south',(0,-37,-361),(72,2,722),soil)
box('Mine bedrock',(0,0,-723),(76,76,2),dark)
marker=bpy.data.objects.new('Mine_Placement',None);guides.objects.link(marker)
marker.location=(0,0,0);marker['OpeningSize']=[72,72];marker['Depth']=720
curve=bpy.data.curves.new('Mine planning label','FONT');curve.body='MINE  /  72 x 72'
curve.align_x='CENTER';curve.align_y='CENTER';curve.size=3
label=bpy.data.objects.new('Mine planning label',curve);guides.objects.link(label)
label.location=(0,0,.38);curve.materials.append(bpy.data.materials['Edge - light limestone'])

# Write material colours into mesh corner colours for reliable FBX colour import.
for ob in structure.all_objects:
 if ob.type!='MESH':continue
 mesh=ob.data
 attr=mesh.color_attributes.get('Color') or mesh.color_attributes.new(name='Color',type='BYTE_COLOR',domain='CORNER')
 mesh.color_attributes.active_color=attr
 for face in mesh.polygons:
  color=mesh.materials[face.material_index].diffuse_color
  for loop in face.loop_indices:attr.data[loop].color=color

manifest=json.loads((OUT/'layout-manifest.json').read_text())
manifest['mine']={'center':[0,0,0],'opening':[72,72],'depth':720,'plaza_outer_size':[100,108],
 'blocks':'Not built; generated by Roblox gameplay','geometry':'Open floor, four shaft walls and bottom bedrock'}
manifest['surface_style']='Smooth flat colour; no stud textures or stud geometry'
manifest['export_contains']='Smooth courtyard layout with an open central mine shaft'
manifest['reserved_zones'].append({'id':'Mine','kind':'Mine','blender_center':[0,0,0],'footprint':[72,72],'roblox_center':[0,0,0]})
(OUT/'layout-manifest.json').write_text(json.dumps(manifest,indent=2))
for ob in scene.objects:ob.select_set(False)
for ob in structure.all_objects:ob.select_set(True)
bpy.context.view_layer.objects.active=root
bpy.ops.export_scene.fbx(filepath=str(OUT/'EnergyCore-CourtyardLayout.fbx'),use_selection=True,
 object_types={'MESH','EMPTY'},axis_forward='-Z',axis_up='Y',global_scale=1,
 apply_unit_scale=True,apply_scale_options='FBX_SCALE_UNITS',colors_type='SRGB',bake_anim=False)
guides.hide_render=False;scene.camera=bpy.data.objects['01 Layout overview']
bpy.ops.wm.save_as_mainfile(filepath=str(OUT/'EnergyCore-CourtyardLayout.blend'))
for camera,filename in [('01 Layout overview','courtyard-overview.png'),('02 Top-down plan','courtyard-plan.png'),('03 Courtyard eye level','courtyard-eye-level.png')]:
 scene.camera=bpy.data.objects[camera];guides.hide_render=camera=='03 Courtyard eye level'
 scene.render.filepath=str(OUT/filename);bpy.ops.render.render(write_still=True)
guides.hide_render=False;scene.camera=bpy.data.objects['01 Layout overview']
bpy.ops.wm.save_as_mainfile(filepath=str(OUT/'EnergyCore-CourtyardLayout.blend'))
print('UPDATED: all studs removed; central 72x72 mine, full 720-depth shaft, surrounding walkways; original 18 footprints retained')
